/* ============================
   LANGUAGE INITIALIZATION
   ============================ */

let currentLang = "en";

try {
  currentLang = localStorage.getItem("gc_lang") || "en";
} catch (e) {}

if (!DICT[currentLang]) {
  currentLang = "en";
}

window.__gramConnectLanguage = currentLang;


/* ============================
   TRANSLATION HELPER
   ============================ */

function t(key) {
  return (DICT[currentLang] && DICT[currentLang][key]) ||
         DICT.en[key] ||
         key;
}

function getSpeechLang() {
  return currentLang === "hi" ? "hi-IN" : "en-IN";
}


/* ============================
   APPLY LANGUAGE TO WEBSITE
   ============================ */

/*
 * FIX: pehle yahan ek alag "applyHaqLanguage" engine aur ek MutationObserver tha.
 * Wo index.html wale applyHaqLanguage se takra raha tha (same naam) aur infinite loop bana sakta tha.
 * Ab Haq Meter ki language sirf index.html ka window.applyHaqLanguage sambhalta hai.
 * Yahan bas use call kiya jata hai.
 */
function applyLang() {
  document.documentElement.lang = currentLang;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  const sel = document.getElementById("lang-select");

  if (sel) {
    sel.value = currentLang;
  }

  window.__gramConnectLanguage = currentLang;

  /* Dynamic website content (scheme cards etc.) dobara banao */
  if (typeof window.onLangChange === "function") {
    try {
      window.onLangChange();
    } catch (e) {
      console.error("Language update error:", e);
    }
  }

  /* Haq Meter ki language (function index.html me defined hai) */
  if (typeof window.applyHaqLanguage === "function") {
    try {
      window.applyHaqLanguage(currentLang);
    } catch (e) {
      console.error("Haq Meter language error:", e);
    }
  }
}


/* ============================
   CHANGE LANGUAGE
   ============================ */

function setLang(lang) {
  if (!DICT[lang]) return;

  currentLang = lang;

  try {
    localStorage.setItem("gc_lang", lang);
  } catch (e) {}

  window.__gramConnectLanguage = lang;

  if (window.speechSynthesis) {
    window.speechSynthesis.cancel();
  }

  applyLang();
}


/* ============================
   INITIALIZE ON PAGE LOAD
   ============================ */

document.addEventListener("DOMContentLoaded", () => {
  const langSelect = document.getElementById("lang-select");

  if (langSelect) {
    langSelect.value = currentLang;

    langSelect.addEventListener("change", event => {
      setLang(event.target.value);
    });
  }

  applyLang();
});